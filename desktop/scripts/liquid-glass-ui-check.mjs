// Real hover, keyboard and dialog interaction in an isolated browser library.
import { chromium } from 'playwright';
import { createServer } from 'vite';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';

const artifacts = resolve('artifacts');
const errors = [], remoteRequests = [], checks = [];
let server, browser, page;
const ready = () => page.waitForFunction(() => document.querySelector('#page-surface')?.classList.contains('page-ready') && !document.querySelector('#page-surface')?.classList.contains('pdf-preview') && !document.querySelector('.pane-enter-active,.pane-leave-active,.sidebar-enter-active,.sidebar-leave-active'));
const shot = name => page.screenshot({ path: resolve(artifacts, name), animations: 'disabled' });
const dialog = () => page.getByRole('dialog', { name: '设置', exact: true });
try {
  await mkdir(artifacts, { recursive: true });
  server = await createServer({ server: { host: '127.0.0.1', port: 1464, strictPort: true, watch: { ignored: ['**/src-tauri/**', '**/artifacts/**'] } } });
  await server.listen();
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 940 }, deviceScaleFactor: 1, colorScheme: 'light' });
  page = await context.newPage();
  page.setDefaultTimeout(20000);
  page.on('pageerror', error => errors.push(error.message));
  await page.route(/^https?:\/\//, route => {
    if (route.request().url().startsWith('http://127.0.0.1:1464')) return route.continue();
    remoteRequests.push(route.request().url()); return route.abort();
  });
  await page.goto('http://127.0.0.1:1464');
  await page.getByRole('button', { name: '打开 阅读工作台指南.md', exact: true }).click();
  await page.locator('.markdown-paper').waitFor();
  await page.getByRole('button', { name: '文档库', exact: true }).click();
  await page.getByRole('button', { name: '打开 PDF 阅读示例.pdf', exact: true }).click();
  await ready();
  await page.getByRole('button', { name: '阅读助手', exact: true }).click();
  await page.locator('.ai-pane').waitFor(); await ready(); await page.waitForTimeout(200);
  const control = page.getByRole('button', { name: '阅读助手', exact: true });
  for (const theme of ['light', 'dark']) {
    if (theme === 'dark') await page.getByTitle('切换深色主题', { exact: true }).click();
    await page.waitForFunction(theme => document.documentElement.dataset.theme === theme, theme);
    const paperBefore = await page.locator('#page-surface').boundingBox();
    const internalLink = page.locator('#page-surface .pdf-link').first();
    await internalLink.hover(); await page.waitForTimeout(200);
    assert.equal(await internalLink.evaluate(element => getComputedStyle(element).boxShadow), 'none', 'Document links must not become glass cards.');
    assert.equal(await internalLink.getAttribute('data-glass-live'), null, 'Glass pointer feedback stays outside document content.');
    const bounds = await control.boundingBox();
    await page.mouse.move(bounds.x + 10, bounds.y + bounds.height / 2);
    await page.waitForTimeout(240);
    const left = await control.screenshot();
    await page.mouse.move(bounds.x + bounds.width - 10, bounds.y + bounds.height / 2);
    await page.waitForTimeout(240);
    const right = await control.screenshot();
    assert.notEqual(Buffer.compare(left, right), 0, 'Moving the cursor changes the rendered glass highlight.');
    assert.deepEqual(await page.locator('#page-surface').boundingBox(), paperBefore, 'Hover never transforms the PDF paper.');
    await page.mouse.move(1430, 920);
    await control.focus();
    await page.keyboard.press('Tab'); await page.keyboard.press('Shift+Tab');
    await page.waitForTimeout(240);
    assert.equal(await control.evaluate(element => document.activeElement === element), true);
    assert.ok(await control.evaluate(element => Number(getComputedStyle(element, '::after').opacity) > 0), 'Keyboard focus illuminates the material.');
    await page.evaluate(() => document.activeElement?.blur());
    await shot(`liquid-glass-main-${theme}.png`);
    checks.push(`${theme}: cursor-dependent rendered control highlight; stable PDF geometry; keyboard focus; full reading screenshot`);
  }
  const originalGlass = await page.locator('html').getAttribute('data-glass');
  await page.evaluate(() => { document.documentElement.dataset.glass = 'solid'; });
  await control.hover(); await page.waitForTimeout(200);
  assert.deepEqual(await control.evaluate(element => ({ translate: getComputedStyle(element).translate, scale: getComputedStyle(element).scale })), { translate: 'none', scale: 'none' });
  assert.equal(await control.evaluate(element => getComputedStyle(element, '::after').content), 'none');
  await page.evaluate(value => { document.documentElement.dataset.glass = value; }, originalGlass);
  checks.push('Opaque glass disables hover movement and reflection; internal PDF links remain transparent document hit areas.');
  await page.getByRole('button', { name: '打开设置', exact: true }).click();
  await dialog().waitFor();
  await page.waitForFunction(() => !document.querySelector('.settings-pop-enter-active'));
  await shot('liquid-glass-settings-dark.png');
  await dialog().getByRole('button', { name: '关闭设置', exact: true }).click();
  await page.waitForFunction(() => !!document.querySelector('.settings-pop-leave-active'));
  assert.equal(await dialog().count(), 1, 'Dialog remains mounted while shrinking.');
  await dialog().waitFor({ state: 'detached' });
  checks.push('Settings closes through a visible shrink transition before unmounting.');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await control.hover(); await page.waitForTimeout(150);
  assert.deepEqual(await control.evaluate(element => ({ translate: getComputedStyle(element).translate, scale: getComputedStyle(element).scale })), { translate: 'none', scale: 'none' });
  await page.getByRole('button', { name: '打开设置', exact: true }).click();
  await dialog().waitFor();
  await page.waitForTimeout(60);
  assert.equal(await dialog().evaluate(element => getComputedStyle(element).transform), 'none');
  await dialog().getByRole('button', { name: '关闭设置', exact: true }).click();
  await dialog().waitFor({ state: 'detached' });
  checks.push('Reduced motion removes popup transforms and retains working dismissal.');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1000, height: 740 });
  await ready();
  assert.ok(await page.locator('.app-topbar').evaluate(element => element.scrollWidth <= element.clientWidth + 1));
  assert.ok(await page.locator('.app-shell').evaluate(element => element.scrollWidth <= element.clientWidth + 1));
  const prompt = page.getByRole('textbox', { name: '向 AI 提问', exact: true });
  const promptBounds = await prompt.boundingBox();
  assert.ok(promptBounds.width > 100 && promptBounds.y + promptBounds.height <= 740, 'Composer remains usable at minimum window width.');
  await shot('liquid-glass-minimum.png');
  checks.push('Minimum 1000px window keeps compact tab strip, floating panes and AI composer usable.');
  assert.deepEqual(errors, []); assert.deepEqual(remoteRequests, []);
  console.log(JSON.stringify({ passed: true, checks, errors, remoteRequests }, null, 2));
} finally {
  await mkdir(artifacts, { recursive: true });
  await writeFile(resolve(artifacts, 'liquid-glass-ui.json'), JSON.stringify({ checks, errors, remoteRequests }, null, 2));
  await browser?.close(); await server?.close();
}
